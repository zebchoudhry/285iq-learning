# Content creation helper functions
def generate_topic_structure(subject, section, topic):
    """Generate the structure for a specific topic"""
    return {
        "id": f"{subject}_{section}_{topic.lower().replace(' ', '_').replace(',', '').replace("'", '')}",
        "subject": subject,
        "section": section,
        "topic_name": topic,
        "display_title": topic,
        "story_hook": "",  # To be filled with child-friendly story
        "explanation": "",  # Main content
        "examples": [],    # Worked examples
        "practice_questions": [],  # Questions with answers
        "memory_tricks": [],  # Mnemonics and tips
        "real_world_connections": [],  # Where this appears in real life
        "video_script": "",  # For your future videos
        "difficulty_level": 1,  # 1=Foundation, 2=Higher
        "estimated_time_minutes": 15,  # How long to complete
        "prerequisites": [],  # What students need to know first
        "exam_board_coverage": ["AQA", "Edexcel", "OCR"]
    }

def count_total_topics():
    """Count how many topics we need to create content for"""
    total = 0
    for subject, data in GCSE_CURRICULUM.items():
        for section, section_data in data["sections"].items():
            total += len(section_data["topics"])
    return total

def get_content_creation_roadmap():
    """Create a roadmap for content creation"""
    roadmap = []
    
    for subject, data in GCSE_CURRICULUM.items():
        subject_topics = []
        for section, section_data in data["sections"].items():
            for topic in section_data["topics"]:
                topic_structure = generate_topic_structure(subject, section, topic)
                subject_topics.append(topic_structure)
        
        roadmap.append({
            "subject": subject,
            "display_name": data["display_name"], 
            "icon": data["icon"],
            "topic_count": len(subject_topics),
            "topics": subject_topics
        })
    
    return roadmap

