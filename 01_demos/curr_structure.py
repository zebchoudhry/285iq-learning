def create_database_import_script():
    """Generate SQL to populate database with curriculum structure"""
    roadmap = get_content_creation_roadmap()
    
    sql_script = """
-- 285IQ Database Population Script
-- This creates all the curriculum structure in your database

-- Insert subjects
INSERT INTO subjects (name, display_name, icon, description) VALUES
('mathematics', 'Mathematics', '🔢', 'GCSE Mathematics curriculum'),
('physics', 'Physics', '⚛️', 'GCSE Physics curriculum'),
('chemistry', 'Chemistry', '🧪', 'GCSE Chemistry curriculum'),
('biology', 'Biology', '🧬', 'GCSE Biology curriculum');

-- Insert sections and topics
"""
    
    for subject_data in roadmap:
        subject = subject_data["subject"]
        
        # Get sections from original curriculum
        sections = GCSE_CURRICULUM[subject]["sections"]
        
        for section_key, section_data in sections.items():
            section_name = section_data["display_name"]
            
            sql_script += f"""
-- {subject.title()} - {section_name}
INSERT INTO sections (subject_name, section_key, display_name) 
VALUES ('{subject}', '{section_key}', '{section_name}');
"""
            
            for topic in section_data["topics"]:
                topic_id = f"{subject}_{section_key}_{topic.lower().replace(' ', '_').replace(',', '').replace("'", '')}"
                
                sql_script += f"""
INSERT INTO topics (id, subject_name, section_key, topic_name, display_title, difficulty_level, estimated_time_minutes)
VALUES ('{topic_id}', '{subject}', '{section_key}', '{topic}', '{topic}', 1, 15);
"""
    
    return sql_script

